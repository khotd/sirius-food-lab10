"""
Доменные исключения приложения.

Файл не зависит ни от fastapi, ни от sqlalchemy: исключения принадлежат
внутренним слоям (бизнес-логике) и поднимаются в service.py. Транспортный
слой (router.py) переводит их в HTTP-статусы.

Все исключения наследуются от ValueError, поэтому остаются совместимыми
с шаблоном из методички (``except ValueError``), но при этом несут
достаточно информации, чтобы router вернул тот же HTTP-статус,
что и MVP-версия (400 / 403 / 404).
"""


class DomainError(ValueError):
    """Базовое исключение нарушения бизнес-правила."""


class NotFoundError(DomainError):
    """Запрошенная сущность не найдена (HTTP 404)."""


class ForbiddenError(DomainError):
    """Операция запрещена для данной сущности (HTTP 403)."""


class BusinessRuleError(DomainError):
    """Нарушено бизнес-правило / некорректные данные (HTTP 400)."""
